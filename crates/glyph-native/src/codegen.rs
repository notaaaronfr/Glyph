//! Native compiler: translates a type-checked Glyph program to C, which the
//! system C compiler turns into a native executable.
//!
//! Every compound expression is lowered into its own temporary, in source order,
//! so evaluation order (and therefore the order of effects and errors) matches
//! the interpreter exactly. The C compiler optimises the temporaries away.

use glyph_front::ast::*;
use glyph_front::{Error, Pos, Sources, Types};
use std::collections::HashMap;

const RUNTIME: &str = include_str!("runtime.c");

/// What the generated program runs on.
#[derive(Clone, Copy, PartialEq)]
pub enum Target {
    /// A normal operating system, through its C library.
    Hosted,
    /// Bare metal: an app for Glyph OS on QEMU's AArch64 `virt` machine. The kernel
    /// itself (kernel.c) is compiled separately and linked with the apps.
    Kernel,
}

/// Effects each target can provide. Programs using others are rejected.
pub fn target_effects(t: Target) -> &'static [&'static str] {
    match t {
        Target::Hosted => &["io", "fs", "time", "rand"],
        Target::Kernel => &["io", "time", "rand"],
    }
}

pub fn emit_c(
    p: &Program,
    types: &Types,
    sources: &Sources,
    target: Target,
) -> Result<String, Error> {
    let available = target_effects(target);
    for f in &p.funcs {
        for (e, pos) in &f.effects {
            if !available.contains(&e.as_str()) {
                return Err(Error::new(
                    "effect",
                    *pos,
                    format!(
                        "`{}` uses effect `{}`, which the kernel target doesn't provide",
                        f.name, e
                    ),
                )
                .hint(format!(
                    "the kernel target provides: {}",
                    available.join(", ")
                )));
            }
        }
    }
    let mut g = Gen {
        types,
        funcs: p.funcs.iter().map(|f| (f.name.as_str(), f)).collect(),
        prog: p,
        records: p.types.iter().map(|t| (t.name.as_str(), t)).collect(),
        rec_started: Default::default(),
        var_types: HashMap::new(),
        drops: vec![],
        temps: vec![],
        movable: None,
        movable_field: None,
        out: String::new(),
        ind: 0,
        n: 0,
        scopes: vec![],
        lits: vec![],
        lit_ids: HashMap::new(),
        tydefs: vec![],
        inst: HashMap::new(),
        instances: HashMap::new(),
        pending: vec![],
        protos: String::new(),
    };
    let main = p.funcs.iter().find(|f| f.name == "main").ok_or_else(|| {
        Error::new(
            "compile",
            Pos::new(1, 1, 0),
            "no `main` function to compile",
        )
        .hint("add `fn main() uses io { ... }`")
    })?;
    if !main.params.is_empty() {
        return Err(Error::new(
            "compile",
            main.pos,
            "`main` must not take parameters",
        ));
    }

    let variant_fields = p
        .enums
        .iter()
        .flat_map(|e| &e.variants)
        .flat_map(|v| &v.fields);
    for (_, ft, pos) in p.types.iter().flat_map(|t| &t.fields).chain(variant_fields) {
        if has_any(ft) {
            return Err(any_error(*pos));
        }
    }
    // Non-generic functions are compiled once each. A generic function is compiled
    // once per combination of type arguments it is called with (monomorphization),
    // as calls to it are discovered.
    let plain: Vec<&Func> = p.funcs.iter().filter(|f| f.tparams.is_empty()).collect();
    for f in &plain {
        g.declare(f, &[], &cid(&f.name))?;
    }
    for f in plain {
        g.func(f, &[], &cid(&f.name))?;
    }
    while let Some((f, targs, cname)) = g.pending.pop() {
        g.func(f, &targs, &cname)?;
    }
    let protos = std::mem::take(&mut g.protos);

    let mut c = String::from("/* Generated by the Glyph compiler. Do not edit. */\n");
    if target == Target::Kernel {
        c += glyph_kernel::API;
    }
    // Every source file, so runtime errors can show the offending line.
    for (i, (_, src)) in sources.0.iter().enumerate() {
        c += &format!("static const char TN_SOURCE_{}[] =\n", i);
        for line in src.split_inclusive('\n') {
            c += &format!("    {}\n", c_str(line));
        }
        c += "    \"\";\n";
    }
    let paths: Vec<String> = sources.0.iter().map(|(path, _)| c_str(path)).collect();
    let srcs: Vec<String> = (0..sources.0.len())
        .map(|i| format!("TN_SOURCE_{}", i))
        .collect();
    c += &format!(
        "static const char *const TN_FILES[] = {{{}}};\n",
        paths.join(", ")
    );
    c += &format!(
        "static const char *const TN_SOURCES[] = {{{}}};\n\n",
        srcs.join(", ")
    );
    c += RUNTIME;
    c += "\n";
    // Types can refer to each other (and themselves, through lists and enums), so
    // declare every descriptor before defining any.
    for (name, _) in &g.tydefs {
        c += &format!("static const tn_type {};\n", name);
    }
    for (_, def) in &g.tydefs {
        c += def;
        c += "\n";
    }
    c += &format!("static tn_str *tn_lits[{}];\n", g.lits.len().max(1));
    c += "static void tn_init_lits(void) {\n";
    for (i, s) in g.lits.iter().enumerate() {
        c += &format!(
            "    tn_lits[{}] = tn_str_static({}, {});\n",
            i,
            c_str(s),
            s.len()
        );
    }
    c += "}\n\n";
    c += &protos;
    c += "\n";
    c += &g.out;
    c += &format!(
        "#ifdef TN_KERNEL\nvoid TN_APP_ENTRY(void) {{\n#else\nint main(void) {{\n#endif\n    tn_init();\n    tn_init_lits();\n    g_main({});\n    tn_memstats();\n    tn_exit(0);\n}}\n",
        loc(main.pos)
    );
    Ok(c)
}

/// A C string literal. Non-ASCII bytes and `?` are escaped (3-digit octal / `\?`) so
/// the output is plain ASCII and free of trigraphs.
fn c_str(s: &str) -> String {
    let mut out = String::from("\"");
    for b in s.bytes() {
        match b {
            b'"' => out += "\\\"",
            b'\\' => out += "\\\\",
            b'\n' => out += "\\n",
            b'\t' => out += "\\t",
            b'?' => out += "\\?",
            0x20..=0x7e => out.push(b as char),
            _ => out += &format!("\\{:03o}", b),
        }
    }
    out.push('"');
    out
}

fn loc(p: Pos) -> String {
    format!("TN_LOC({}, {}, {})", p.file, p.line, p.col)
}

/// A Glyph name as part of a C identifier: module paths use `.`, which C doesn't allow.
fn cid(name: &str) -> String {
    name.replace('.', "__")
}

fn plist(params: &[String]) -> String {
    if params.is_empty() {
        "void".into()
    } else {
        params.join(", ")
    }
}

fn with_loc(params: &[String]) -> Vec<String> {
    let mut v = params.to_vec();
    v.push("tn_loc at".into());
    v
}

fn has_any(t: &Type) -> bool {
    match t {
        Type::Any => true,
        Type::List(x) => has_any(x),
        Type::Record(_, xs) | Type::Enum(_, xs) => xs.iter().any(has_any),
        _ => false,
    }
}

fn any_error(pos: Pos) -> Error {
    Error::new(
        "compile",
        pos,
        "type `Any` is not supported by the native compiler yet",
    )
    .hint("use a concrete type, or run the program with `glyph run`")
}

/// A short, unique, C-identifier-safe name for a concrete type, e.g. `Option[Int]`
/// is `e6Option1i`. Names are length-prefixed, so the encoding is unambiguous.
fn mangle(t: &Type) -> String {
    match t {
        Type::Int => "i".into(),
        Type::Str => "s".into(),
        Type::Bool => "b".into(),
        Type::Unit => "u".into(),
        Type::Any => "a".into(),
        Type::List(x) => format!("l{}", mangle(x)),
        Type::Record(n, args) | Type::Enum(n, args) => {
            let kind = if matches!(t, Type::Record(..)) {
                'r'
            } else {
                'e'
            };
            let args: String = args.iter().map(mangle).collect();
            let n = cid(n);
            format!("{}{}{}{}{}", kind, n.len(), n, t_args_len(t), args)
        }
        Type::Param(p) => format!("p{}{}", p.len(), cid(p)),
    }
}

fn t_args_len(t: &Type) -> usize {
    match t {
        Type::Record(_, a) | Type::Enum(_, a) => a.len(),
        _ => 0,
    }
}

fn to_val(t: &Type, atom: &str) -> String {
    match t {
        Type::Int => format!("TN_I({})", atom),
        Type::Bool => format!("TN_B({})", atom),
        Type::Unit => "TN_I(0)".into(),
        _ => format!("TN_P({})", atom),
    }
}

fn from_val(t: &Type, v: &str) -> String {
    match t {
        Type::Int => format!("({}).i", v),
        Type::Bool => format!("({}).b", v),
        Type::Unit => "(tn_unit)0".into(),
        Type::Str => format!("((tn_str *)({}).p)", v),
        Type::Record(..) => format!("((tn_rec *)({}).p)", v),
        Type::Enum(..) => format!("((tn_enum *)({}).p)", v),
        _ => format!("((tn_list *)({}).p)", v),
    }
}

/// A lowered expression: a C expression that is cheap to repeat (a variable or a
/// literal). `owned` is true for a temporary holding a reference that must be
/// released (or moved); variables and literals are borrowed.
struct Atom {
    c: String,
    owned: bool,
}

/// Values that live on the heap and are reference counted.
fn is_heap(t: &Type) -> bool {
    matches!(
        t,
        Type::Str | Type::List(_) | Type::Record(..) | Type::Enum(..)
    )
}

fn heap_ctype(t: &Type) -> &'static str {
    match t {
        Type::Str => "tn_str *",
        Type::List(_) => "tn_list *",
        Type::Record(..) => "tn_rec *",
        _ => "tn_enum *",
    }
}

fn elem_of(t: &Type) -> Type {
    match t {
        Type::List(x) => (**x).clone(),
        _ => Type::Any,
    }
}

struct Gen<'a> {
    types: &'a Types,
    funcs: HashMap<&'a str, &'a Func>,
    out: String,
    ind: usize,
    n: usize,
    /// Glyph variable name -> C variable name, innermost scope last.
    scopes: Vec<HashMap<String, String>>,
    /// C variable name -> Glyph type. C names are unique within a function.
    var_types: HashMap<String, Type>,
    /// Per scope: heap variables to drop when the scope ends.
    drops: Vec<Vec<String>>,
    /// Per statement (and `and`/`or` right side): owned temporaries to drop.
    temps: Vec<Vec<(String, Type)>>,
    /// The variable whose single read in the current assignment takes its value.
    movable: Option<String>,
    /// Likewise for `p.f = ...p.f...`: (C variable, field) whose read moves the field out.
    movable_field: Option<(String, String)>,
    records: HashMap<&'a str, &'a TypeDecl>,
    prog: &'a Program,
    rec_started: std::collections::HashSet<String>,
    lits: Vec<String>,
    lit_ids: HashMap<String, usize>,
    /// Type descriptors: (C name, definition).
    tydefs: Vec<(String, String)>,
    /// Type arguments of the generic function instance being compiled.
    inst: HashMap<String, Type>,
    /// Generic instances created so far: key -> C name.
    instances: HashMap<String, String>,
    /// Generic instances still to be compiled.
    pending: Vec<(&'a Func, Vec<Type>, String)>,
    protos: String,
}

impl<'a> Gen<'a> {
    fn line(&mut self, s: impl AsRef<str>) {
        for _ in 0..self.ind {
            self.out += "    ";
        }
        self.out += s.as_ref();
        self.out += "\n";
    }

    fn fresh(&mut self, prefix: &str) -> String {
        self.n += 1;
        format!("{}{}", prefix, self.n)
    }

    /// The concrete type of `e` in the function instance being compiled.
    fn ty(&self, e: &Expr) -> Type {
        self.types.of(e).subst(&self.inst)
    }

    fn ctype(&self, t: &Type, pos: Pos) -> Result<&'static str, Error> {
        Ok(match t {
            Type::Int => "int64_t",
            Type::Bool => "bool",
            Type::Unit => "tn_unit",
            Type::Str => "tn_str *",
            Type::List(x) => {
                self.ctype(x, pos)?;
                "tn_list *"
            }
            Type::Record(..) => "tn_rec *",
            Type::Enum(..) => "tn_enum *",
            Type::Any => return Err(any_error(pos)),
            Type::Param(p) => {
                return Err(Error::new(
                    "compile",
                    pos,
                    format!("internal error: unresolved type parameter `{}`", p),
                ))
            }
        })
    }

    /// `&TY_...` descriptor for generic runtime operations (printing, equality).
    fn tydesc(&mut self, t: &Type) -> String {
        let name = match t {
            Type::Unit | Type::Any | Type::Param(_) => "TY_u".to_string(),
            _ => format!("TY_{}", mangle(t)),
        };
        // Mark before recursing: a type may contain itself through a list or enum.
        // List[Int] and List[Str] are defined by the runtime.
        if !matches!(t, Type::List(_) | Type::Record(..) | Type::Enum(..))
            || name == "TY_li"
            || name == "TY_ls"
            || !self.rec_started.insert(name.clone())
        {
            return format!("&{}", name);
        }
        let id = mangle(t);
        let def = match t {
            Type::List(x) => {
                let inner = self.tydesc(x);
                format!("static const tn_type {} = {{TN_LIST, {}}};", name, inner)
            }
            Type::Record(n, args) => {
                let decl = self.records[n.as_str()];
                let b = bindings(&decl.params, args);
                let fields: Vec<(String, Type)> = decl
                    .fields
                    .iter()
                    .map(|(f, ft, _)| (f.clone(), ft.subst(&b)))
                    .collect();
                if fields.is_empty() {
                    format!(
                        "static const tn_type {} = {{TN_RECORD, 0, {}, 0, 0, 0}};",
                        name,
                        c_str(&t.to_string())
                    )
                } else {
                    let tables = self.field_tables(&id, &fields);
                    format!(
                        "{}\nstatic const tn_type {} = {{TN_RECORD, 0, {}, {}, FN_{id}, FT_{id}}};",
                        tables,
                        name,
                        c_str(n),
                        fields.len(),
                        id = id
                    )
                }
            }
            Type::Enum(n, args) => {
                let decl = self.enum_decl(n);
                let b = bindings(&decl.params, args);
                let mut defs = vec![];
                let mut variants = vec![];
                for v in &decl.variants {
                    if v.fields.is_empty() {
                        variants.push(format!("{{{}, 0, 0, 0}}", c_str(&v.name)));
                        continue;
                    }
                    let fields: Vec<(String, Type)> = v
                        .fields
                        .iter()
                        .map(|(f, ft, _)| (f.clone(), ft.subst(&b)))
                        .collect();
                    let vid = format!("{}_{}", id, cid(&v.name));
                    defs.push(self.field_tables(&vid, &fields));
                    variants.push(format!(
                        "{{{}, {}, FN_{vid}, FT_{vid}}}",
                        c_str(&v.name),
                        fields.len(),
                        vid = vid
                    ));
                }
                defs.push(format!(
                    "static const tn_variant VR_{id}[] = {{{}}};\n\
                     static const tn_type {} = {{TN_ENUM, 0, {}, {}, 0, 0, VR_{id}}};",
                    variants.join(", "),
                    name,
                    c_str(n),
                    decl.variants.len(),
                    id = id
                ));
                defs.join("\n")
            }
            _ => unreachable!(),
        };
        self.tydefs.push((name.clone(), def));
        format!("&{}", name)
    }

    /// The `FN_<id>` (field names) and `FT_<id>` (field types) tables of a record or variant.
    fn field_tables(&mut self, id: &str, fields: &[(String, Type)]) -> String {
        let names: Vec<String> = fields.iter().map(|f| c_str(&f.0)).collect();
        let mut types = vec![];
        for (_, ft) in fields {
            types.push(self.tydesc(ft));
        }
        format!(
            "static const char *const FN_{id}[] = {{{}}};\n\
             static const tn_type *const FT_{id}[] = {{{}}};",
            names.join(", "),
            types.join(", "),
            id = id
        )
    }

    fn enum_decl(&self, n: &str) -> &'a EnumDecl {
        let prog = self.prog;
        prog.enums.iter().find(|e| e.name == n).expect("checked")
    }

    /// The concrete field types of record or variant fields, given the value's type.
    fn field_ty(&self, owner: &Type, params: &[String], ft: &Type) -> Type {
        match owner {
            Type::Record(_, args) | Type::Enum(_, args) => ft.subst(&bindings(params, args)),
            _ => ft.clone(),
        }
    }

    fn lit(&mut self, s: &str) -> String {
        let id = match self.lit_ids.get(s) {
            Some(id) => *id,
            None => {
                self.lits.push(s.to_string());
                self.lit_ids.insert(s.to_string(), self.lits.len() - 1);
                self.lits.len() - 1
            }
        };
        format!("tn_lits[{}]", id)
    }

    fn lookup(&self, n: &str) -> String {
        self.scopes
            .iter()
            .rev()
            .find_map(|s| s.get(n))
            .cloned()
            .expect("checker guarantees variables exist")
    }

    /// A new temporary holding `init`. Heap temporaries own their value and are
    /// dropped at the end of the statement unless something takes ownership first.
    fn tmp(&mut self, t: &Type, pos: Pos, init: String) -> Result<Atom, Error> {
        let ct = self.ctype(t, pos)?;
        let name = self.fresh("t");
        self.line(format!("{} {} = {};", ct, name, init));
        let owned = is_heap(t);
        if owned {
            self.temps
                .last_mut()
                .expect("temporaries live in a statement")
                .push((name.clone(), t.clone()));
        }
        Ok(Atom { c: name, owned })
    }

    /// A C expression for a new reference to `a`'s value: moves an owned
    /// temporary (no count change), or dups a borrowed value.
    fn own(&mut self, a: &Atom, t: &Type) -> String {
        if !is_heap(t) {
            return a.c.clone();
        }
        if a.owned && self.take_temp(&a.c) {
            return a.c.clone();
        }
        format!("({})tn_dup({})", heap_ctype(t), a.c)
    }

    /// A C expression for an owned copy of the borrowed value `v` of type `t`.
    fn dup_of(t: &Type, v: String) -> String {
        if is_heap(t) {
            format!("({})tn_dup({})", heap_ctype(t), v)
        } else {
            v
        }
    }

    /// Takes temporary `c` out of the drop lists (its ownership moves elsewhere).
    fn take_temp(&mut self, c: &str) -> bool {
        for frame in self.temps.iter_mut().rev() {
            if let Some(i) = frame.iter().position(|(n, _)| n == c) {
                frame.remove(i);
                return true;
            }
        }
        false
    }

    /// Drops the current statement's remaining temporaries.
    fn drop_temps(&mut self) {
        let frame = std::mem::take(self.temps.last_mut().expect("in a statement"));
        for (c, _) in frame.iter().rev() {
            self.line(format!("tn_drop({});", c));
        }
    }

    fn push_scope(&mut self) {
        self.scopes.push(HashMap::new());
        self.drops.push(vec![]);
    }

    /// Ends a scope, dropping the heap variables declared in it.
    fn pop_scope(&mut self) {
        self.scopes.pop();
        let vars = self.drops.pop().unwrap_or_default();
        for c in vars.iter().rev() {
            self.line(format!("tn_drop({});", c));
        }
    }

    /// Declares a variable that owns its value until its scope ends.
    fn declare_var(&mut self, name: &str, c: String, t: Type) {
        if is_heap(&t) {
            self.drops.last_mut().expect("in a scope").push(c.clone());
        }
        self.var_types.insert(c.clone(), t);
        self.scopes
            .last_mut()
            .expect("in a scope")
            .insert(name.to_string(), c);
    }

    fn signature(
        &self,
        f: &Func,
        b: &HashMap<String, Type>,
    ) -> Result<(&'static str, Vec<String>), Error> {
        let ret = self.ctype(&f.ret.subst(b), f.pos)?;
        let params = f
            .params
            .iter()
            .map(|p| {
                Ok(format!(
                    "{} p_{}",
                    self.ctype(&p.ty.subst(b), f.pos)?,
                    p.name
                ))
            })
            .collect::<Result<_, Error>>()?;
        Ok((ret, params))
    }

    /// Adds the C prototypes for function `f` instantiated with `targs`, as `cname`.
    fn declare(&mut self, f: &Func, targs: &[Type], cname: &str) -> Result<(), Error> {
        let (ret, params) = self.signature(f, &bindings(&f.tparams, targs))?;
        self.protos += &format!("static {} gb_{}({});\n", ret, cname, plist(&params));
        self.protos += &format!(
            "static {} g_{}({});\n",
            ret,
            cname,
            plist(&with_loc(&params))
        );
        Ok(())
    }

    /// The C name of generic function `f` instantiated with `targs`, queuing it for
    /// compilation the first time it is needed.
    fn instance(&mut self, f: &'a Func, targs: Vec<Type>, pos: Pos) -> Result<String, Error> {
        let key = format!(
            "{}__{}",
            cid(&f.name),
            targs.iter().map(mangle).collect::<String>()
        );
        if let Some(c) = self.instances.get(&key) {
            return Ok(c.clone());
        }
        if targs.iter().any(has_any) {
            return Err(any_error(pos));
        }
        if self.instances.len() >= 1000 {
            return Err(Error::new(
                "compile",
                pos,
                format!("too many versions of `{}` needed", f.name),
            )
            .hint("a generic function that calls itself with a bigger type can't be compiled natively"));
        }
        self.declare(f, &targs, &key)?;
        self.instances.insert(key.clone(), key.clone());
        self.pending.push((f, targs, key.clone()));
        Ok(key)
    }

    /// Each Glyph function becomes two C functions: `gb_f` holds the body, and `g_f`
    /// wraps it with the recursion limit and the `requires` / `ensures` checks.
    /// Both take ownership of their arguments and return an owned result.
    fn func(&mut self, f: &'a Func, targs: &[Type], cname: &str) -> Result<(), Error> {
        self.inst = bindings(&f.tparams, targs);
        let (ret, params) = self.signature(f, &self.inst.clone())?;
        let fret = f.ret.subst(&self.inst);
        let fparams: Vec<(String, Type)> = f
            .params
            .iter()
            .map(|p| (p.name.clone(), p.ty.subst(&self.inst)))
            .collect();

        self.line(format!(
            "static {} gb_{}({}) {{",
            ret,
            cname,
            plist(&params)
        ));
        self.ind = 1;
        self.scopes = vec![];
        self.drops = vec![];
        self.temps = vec![];
        self.push_scope();
        for (name, ty) in &fparams {
            self.declare_var(name, format!("p_{}", name), ty.clone());
        }
        self.block(&f.body)?;
        if fret == Type::Unit {
            self.pop_scope();
            self.line("return 0;");
        } else {
            self.scopes.pop();
            self.drops.pop();
            self.line("__builtin_unreachable(); /* the checker guarantees a return */");
        }
        self.ind = 0;
        self.line("}\n");

        self.line(format!(
            "static {} g_{}({}) {{",
            ret,
            cname,
            plist(&with_loc(&params))
        ));
        self.ind = 1;
        self.line(format!(
            "if (++tn_depth > TN_MAX_DEPTH) tn_fail_depth(at, {});",
            c_str(&f.name)
        ));
        let inputs = if f.params.is_empty() {
            "\"no arguments\"".to_string()
        } else {
            let names: Vec<String> = f.params.iter().map(|p| c_str(&p.name)).collect();
            let mut vals = vec![];
            for (name, ty) in &fparams {
                let d = self.tydesc(ty);
                vals.push(format!(
                    "tn_to_str({}, {}, true)",
                    to_val(ty, &format!("p_{}", name)),
                    d
                ));
            }
            format!(
                "tn_inputs({}, (const char *[]){{{}}}, (tn_str *[]){{{}}})",
                f.params.len(),
                names.join(", "),
                vals.join(", ")
            )
        };
        // Contracts borrow the arguments; the wrapper still owns them.
        let param_scope: HashMap<String, String> = fparams
            .iter()
            .map(|(n, _)| (n.clone(), format!("p_{}", n)))
            .collect();
        for (n, ty) in &fparams {
            self.var_types.insert(format!("p_{}", n), ty.clone());
        }
        // A failed precondition is the caller's fault: report it at the call site.
        self.scopes = vec![param_scope.clone()];
        self.drops = vec![vec![]];
        for c in &f.requires {
            self.temps.push(vec![]);
            let a = self.expr(c)?;
            self.drop_temps();
            self.temps.pop();
            let msg = format!("precondition of `{}` violated: `{}`", f.name, c.text);
            self.line(format!(
                "if (!{}) tn_fail(\"contract\", at, {}, tn_fmt(\"called with %s\", {}));",
                a.c,
                c_str(&msg),
                inputs
            ));
        }
        // The body consumes its arguments. If `ensures` needs them afterwards, it gets
        // its own references.
        let keep = !f.ensures.is_empty();
        let args: Vec<String> = fparams
            .iter()
            .map(|(n, ty)| {
                let p = format!("p_{}", n);
                if keep {
                    Self::dup_of(ty, p)
                } else {
                    p
                }
            })
            .collect();
        self.line(format!(
            "{} result_ = gb_{}({});",
            ret,
            cname,
            args.join(", ")
        ));
        // A failed postcondition is the function's own fault: report it at the clause.
        let mut post_scope = param_scope;
        post_scope.insert("result".into(), "result_".into());
        self.var_types.insert("result_".into(), fret.clone());
        self.scopes = vec![post_scope];
        let ret_desc = self.tydesc(&fret);
        for c in &f.ensures {
            self.temps.push(vec![]);
            let a = self.expr(c)?;
            self.drop_temps();
            self.temps.pop();
            let msg = format!("postcondition of `{}` violated: `{}`", f.name, c.text);
            self.line(format!(
                "if (!{}) tn_fail(\"contract\", {}, {}, tn_fmt(\"called with %s, returned %s\", {}, tn_to_str({}, {}, true)->data));",
                a.c,
                loc(c.pos),
                c_str(&msg),
                inputs,
                to_val(&fret, "result_"),
                ret_desc
            ));
        }
        if keep {
            for (n, ty) in &fparams {
                if is_heap(ty) {
                    self.line(format!("tn_drop(p_{});", n));
                }
            }
        }
        self.line("tn_depth--;");
        self.line("return result_;");
        self.ind = 0;
        self.line("}\n");
        Ok(())
    }

    fn block(&mut self, stmts: &[Stmt]) -> Result<(), Error> {
        self.push_scope();
        for s in stmts {
            self.stmt(s)?;
        }
        self.pop_scope();
        Ok(())
    }

    fn nested(&mut self, stmts: &[Stmt]) -> Result<(), Error> {
        self.ind += 1;
        self.block(stmts)?;
        self.ind -= 1;
        Ok(())
    }

    /// Each statement gets a frame of temporaries, dropped when it ends.
    fn stmt(&mut self, s: &Stmt) -> Result<(), Error> {
        self.temps.push(vec![]);
        self.stmt_inner(s)?;
        self.drop_temps();
        self.temps.pop();
        Ok(())
    }

    /// `return`: drops everything the function still owns, except what is returned.
    fn emit_return(&mut self, value: Option<(&Expr, Atom)>) -> Result<(), Error> {
        let mut moved_var = None;
        let ret = match value {
            Some((e, a)) => {
                let t = self.ty(e);
                if is_heap(&t) && !a.owned && self.drops.iter().flatten().any(|c| *c == a.c) {
                    // Returning a variable: move it out instead of dup + drop.
                    moved_var = Some(a.c.clone());
                    a.c
                } else {
                    let v = self.own(&a, &t);
                    let ct = self.ctype(&t, e.pos)?;
                    let r = self.fresh("r");
                    self.line(format!("{} {} = {};", ct, r, v));
                    r
                }
            }
            None => "0".into(),
        };
        let temps: Vec<String> = self
            .temps
            .iter()
            .flatten()
            .map(|(c, _)| c.clone())
            .collect();
        for c in temps.iter().rev() {
            self.line(format!("tn_drop({});", c));
        }
        let vars: Vec<String> = self.drops.iter().flatten().cloned().collect();
        for c in vars.iter().rev() {
            if Some(c) != moved_var.as_ref() {
                self.line(format!("tn_drop({});", c));
            }
        }
        self.line(format!("return {};", ret));
        Ok(())
    }

    fn stmt_inner(&mut self, s: &Stmt) -> Result<(), Error> {
        match s {
            Stmt::Let(n, ann, e) => {
                let a = self.expr(e)?;
                let t = match ann {
                    Some(a) => a.subst(&self.inst),
                    None => self.ty(e),
                };
                let ct = self.ctype(&t, e.pos)?;
                let v = self.fresh(&format!("v_{}_", n));
                let init = self.own(&a, &t);
                self.line(format!("{} {} = {};", ct, v, init));
                self.declare_var(n, v, t);
            }
            Stmt::Match(scrutinee, arms, _) => {
                let st = self.ty(scrutinee);
                let a = self.expr(scrutinee)?;
                // Hold a reference for the whole match, so arms may reassign the variable.
                self.push_scope();
                let m = self.fresh("m");
                let init = self.own(&a, &st);
                self.line(format!("tn_enum *{} = {};", m, init));
                self.drops.last_mut().unwrap().push(m.clone());
                self.drop_temps();
                let Type::Enum(en, _) = &st else {
                    return Err(Error::new(
                        "compile",
                        scrutinee.pos,
                        "`match` on a non-enum",
                    ));
                };
                let decl = self.enum_decl(en);
                for (k, arm) in arms.iter().enumerate() {
                    let cond = match &arm.pattern {
                        Pattern::Wildcard(_) => "1".to_string(),
                        Pattern::Variant(v, _, _) => {
                            let tag = decl
                                .variants
                                .iter()
                                .position(|x| &x.name == v)
                                .expect("checked");
                            format!("{}->tag == {}", m, tag)
                        }
                    };
                    self.line(format!(
                        "{}if ({}) {{",
                        if k == 0 { "" } else { "} else " },
                        cond
                    ));
                    self.ind += 1;
                    self.push_scope();
                    if let Pattern::Variant(v, binds, _) = &arm.pattern {
                        let var = decl
                            .variants
                            .iter()
                            .find(|x| &x.name == v)
                            .expect("checked");
                        for (f, name, pos) in binds {
                            let (i, ft) = var.field(f).expect("checked");
                            let ft = self.field_ty(&st, &decl.params, ft);
                            let ct = self.ctype(&ft, *pos)?;
                            let cv = self.fresh(&format!("v_{}_", name));
                            let init =
                                Self::dup_of(&ft, from_val(&ft, &format!("{}->f[{}]", m, i)));
                            self.line(format!("{} {} = {};", ct, cv, init));
                            self.declare_var(name, cv, ft);
                        }
                    }
                    self.block(&arm.body)?;
                    self.pop_scope();
                    self.ind -= 1;
                }
                if !arms.is_empty() {
                    self.line("}");
                }
                self.pop_scope();
            }
            Stmt::SetField(n, path, e, _) => {
                let v = self.lookup(n);
                let t = self.var_types[&v].clone();
                // `p.f = g(p.f)`: the single read of `p.f` moves the field out of `p`,
                // so `g` can update it in place (e.g. `c.log = push(c.log, x)`).
                if path.len() == 1 && reads_once(e, n) && reads_field(e, n, &path[0].0) {
                    self.movable_field = Some((v.clone(), path[0].0.clone()));
                }
                let a = self.expr(e)?;
                self.movable_field = None;
                let vt = self.ty(e);
                let val = self.own(&a, &vt);
                // The variable's reference moves into the update, which reuses the
                // record's memory when nothing else shares it.
                let updated = self.set_path(&v, &t, path, &val)?;
                self.drop_temps();
                self.line(format!("{} = {};", v, updated));
            }
            Stmt::Assign(n, e, _) => {
                let v = self.lookup(n);
                let t = self.var_types[&v].clone();
                // `x = f(..x..)` with a single unconditional read of `x`: that read takes
                // the old value (no dup), so in-place updates see a unique owner.
                let movable = is_heap(&t) && reads_once(e, n);
                if movable {
                    self.movable = Some(v.clone());
                }
                let a = self.expr(e)?;
                self.movable = None;
                let new = self.own(&a, &t);
                let ct = self.ctype(&t, e.pos)?;
                let nv = self.fresh("n");
                self.line(format!("{} {} = {};", ct, nv, new));
                // The old value is either moved already, or among the temporaries, or
                // (when not movable) still owned by the variable.
                self.drop_temps();
                if is_heap(&t) && !movable {
                    self.line(format!("tn_drop({});", v));
                }
                self.line(format!("{} = {};", v, nv));
            }
            Stmt::Expr(e) => {
                let a = self.expr(e)?;
                self.line(format!("(void){};", a.c));
            }
            Stmt::If(c, then, els) => {
                let a = self.expr(c)?;
                self.drop_temps();
                self.line(format!("if ({}) {{", a.c));
                self.nested(then)?;
                if let Some(b) = els {
                    self.line("} else {");
                    self.nested(b)?;
                }
                self.line("}");
            }
            Stmt::While(c, body) => {
                self.line("while (1) {");
                self.ind += 1;
                self.temps.push(vec![]);
                let a = self.expr(c)?;
                self.drop_temps();
                self.temps.pop();
                self.line(format!("if (!{}) break;", a.c));
                self.ind -= 1;
                self.nested(body)?;
                self.line("}");
            }
            Stmt::For(n, e, body, _) => {
                let t = self.ty(e);
                let a = self.expr(e)?;
                let (elem, src) = match &t {
                    Type::Str => (Type::Str, format!("tn_str_chars({})", a.c)),
                    t => (elem_of(t), self.own(&a, t)),
                };
                let ct = self.ctype(&elem, e.pos)?;
                // The loop holds its own reference to the list, so the body may
                // reassign the variable being iterated.
                self.push_scope();
                let (it, i) = (self.fresh("it"), self.fresh("i"));
                self.line(format!("tn_list *{} = {};", it, src));
                self.drops.last_mut().unwrap().push(it.clone());
                self.drop_temps();
                self.line(format!(
                    "for (int64_t {i} = 0; {i} < {it}->len; {i}++) {{",
                    i = i,
                    it = it
                ));
                self.ind += 1;
                self.push_scope();
                let v = self.fresh(&format!("v_{}_", n));
                let item = Self::dup_of(
                    &elem,
                    from_val(&elem, &format!("tn_list_item({}, {})", it, i)),
                );
                self.line(format!("{} {} = {};", ct, v, item));
                self.declare_var(n, v, elem.clone());
                self.block(body)?;
                self.pop_scope();
                self.ind -= 1;
                self.line("}");
                self.pop_scope();
            }
            Stmt::Return(e, _) => {
                let value = match e {
                    Some(e) => Some((e, self.expr(e)?)),
                    None => None,
                };
                self.emit_return(value)?;
            }
            Stmt::Assert(e) => {
                let msg = c_str(&format!("assertion failed: `{}`", e.text));
                match &e.kind {
                    ExprKind::Binary(op, l, r) if !matches!(op, BinOp::And | BinOp::Or) => {
                        let (a, b) = (self.expr(l)?, self.expr(r)?);
                        let (lt, rt) = (self.ty(l), self.ty(r));
                        let c = self.binop(*op, &lt, &a.c, &b.c, e)?;
                        let (ld, rd) = (self.tydesc(&lt), self.tydesc(&rt));
                        self.line(format!(
                            "if (!{}) tn_fail(\"assertion\", {}, {}, tn_fmt(\"left side = %s, right side = %s\", tn_to_str({}, {}, true)->data, tn_to_str({}, {}, true)->data));",
                            c, loc(e.pos), msg, to_val(&lt, &a.c), ld, to_val(&rt, &b.c), rd
                        ));
                    }
                    _ => {
                        let a = self.expr(e)?;
                        self.line(format!(
                            "if (!{}) tn_fail(\"assertion\", {}, {}, NULL);",
                            a.c,
                            loc(e.pos),
                            msg
                        ));
                    }
                }
            }
        }
        Ok(())
    }

    /// Lowers `e` and returns an atom (a variable or literal) holding its value.
    fn expr(&mut self, e: &Expr) -> Result<Atom, Error> {
        let t = self.ty(e);
        let plain = |c: String| Atom { c, owned: false };
        Ok(match &e.kind {
            ExprKind::Int(n) => plain(format!("INT64_C({})", n)),
            ExprKind::Bool(b) => plain(b.to_string()),
            ExprKind::Str(s) => plain(self.lit(s)),
            ExprKind::Var(n) => {
                let c = self.lookup(n);
                if self.movable.as_ref() == Some(&c) {
                    // The single read in `x = ...`: take x's reference as a temporary.
                    self.movable = None;
                    self.temps.last_mut().unwrap().push((c.clone(), t.clone()));
                    Atom { c, owned: true }
                } else {
                    plain(c)
                }
            }
            ExprKind::List(items) => {
                let elem = elem_of(&t);
                let mut atoms = vec![];
                for it in items {
                    atoms.push(self.expr(it)?);
                }
                let vals: Vec<String> = atoms
                    .iter()
                    .map(|a| {
                        let v = self.own(a, &elem);
                        to_val(&elem, &v)
                    })
                    .collect();
                let d = self.tydesc(&t);
                let init = if vals.is_empty() {
                    format!("tn_list_new({}, 0)", d)
                } else {
                    format!(
                        "tn_list_from({}, {}, (tn_val[]){{{}}})",
                        d,
                        vals.len(),
                        vals.join(", ")
                    )
                };
                self.tmp(&t, e.pos, init)?
            }
            ExprKind::Unary(UnOp::Neg, x) => {
                let a = self.expr(x)?;
                self.tmp(
                    &t,
                    e.pos,
                    format!("tn_neg({}, {}, {})", a.c, loc(e.pos), c_str(&e.text)),
                )?
            }
            ExprKind::Unary(UnOp::Not, x) => {
                let a = self.expr(x)?;
                self.tmp(&t, e.pos, format!("!{}", a.c))?
            }
            ExprKind::Binary(op @ (BinOp::And | BinOp::Or), l, r) => {
                // Short-circuit: the right side's temporaries live inside the `if`.
                let a = self.expr(l)?;
                let name = self.fresh("t");
                self.line(format!("bool {} = {};", name, a.c));
                self.line(format!(
                    "if ({}{}) {{",
                    if *op == BinOp::And { "" } else { "!" },
                    name
                ));
                self.ind += 1;
                self.temps.push(vec![]);
                let b = self.expr(r)?;
                self.line(format!("{} = {};", name, b.c));
                self.drop_temps();
                self.temps.pop();
                self.ind -= 1;
                self.line("}");
                plain(name)
            }
            ExprKind::Binary(op, l, r) => {
                let (a, b) = (self.expr(l)?, self.expr(r)?);
                let lt = self.ty(l);
                let init = self.binop(*op, &lt, &a.c, &b.c, e)?;
                self.tmp(&t, e.pos, init)?
            }
            ExprKind::Record(name, fields) => {
                // Evaluate in source order, store in declaration order.
                let mut atoms = HashMap::new();
                for (f, fe, _) in fields {
                    let a = self.expr(fe)?;
                    atoms.insert(f.as_str(), a);
                }
                let decl = self.records[name.as_str()];
                let mut vals = vec![];
                for (f, ft, _) in &decl.fields {
                    let ft = self.field_ty(&t, &decl.params, ft);
                    let v = self.own(&atoms[f.as_str()], &ft);
                    vals.push(to_val(&ft, &v));
                }
                let d = self.tydesc(&t);
                let init = if vals.is_empty() {
                    format!("tn_rec_new({}, 0, NULL)", d)
                } else {
                    format!(
                        "tn_rec_new({}, {}, (tn_val[]){{{}}})",
                        d,
                        vals.len(),
                        vals.join(", ")
                    )
                };
                self.tmp(&t, e.pos, init)?
            }
            ExprKind::Variant(name, fields) => {
                let mut atoms = HashMap::new();
                for (f, fe, _) in fields {
                    let a = self.expr(fe)?;
                    atoms.insert(f.as_str(), a);
                }
                let (decl, tag) = self.prog.variant(name).expect("checked");
                let mut vals = vec![];
                for (f, ft, _) in &decl.variants[tag].fields {
                    let ft = self.field_ty(&t, &decl.params, ft);
                    let v = self.own(&atoms[f.as_str()], &ft);
                    vals.push(to_val(&ft, &v));
                }
                let d = self.tydesc(&t);
                let init = if vals.is_empty() {
                    format!("tn_enum_new({}, {}, 0, NULL)", d, tag)
                } else {
                    format!(
                        "tn_enum_new({}, {}, {}, (tn_val[]){{{}}})",
                        d,
                        tag,
                        vals.len(),
                        vals.join(", ")
                    )
                };
                self.tmp(&t, e.pos, init)?
            }
            ExprKind::Field(target, f)
                if matches!(&target.kind, ExprKind::Var(n)
                    if self.movable_field.as_ref() == Some(&(self.lookup(n), f.clone()))) =>
            {
                let (c, _) = self.movable_field.take().expect("checked above");
                let Type::Record(rn, _) = self.ty(target) else {
                    return Err(Error::new("compile", e.pos, "field access on a non-record"));
                };
                let (i, _) = self.records[rn.as_str()].field(f).expect("checked");
                let init = from_val(&t, &format!("tn_rec_take({}, {})", c, i));
                self.tmp(&t, e.pos, init)?
            }
            ExprKind::Field(target, f) => {
                let a = self.expr(target)?;
                let Type::Record(rn, _) = self.ty(target) else {
                    return Err(Error::new("compile", e.pos, "field access on a non-record"));
                };
                let (i, _) = self.records[rn.as_str()].field(f).expect("checked");
                let init = Self::dup_of(&t, from_val(&t, &format!("{}->f[{}]", a.c, i)));
                self.tmp(&t, e.pos, init)?
            }
            ExprKind::Index(target, idx) => {
                let (a, i) = (self.expr(target)?, self.expr(idx)?);
                let init = match self.ty(target) {
                    Type::Str => format!("tn_str_at({}, {}, {})", a.c, i.c, loc(e.pos)),
                    tt => Self::dup_of(
                        &t,
                        from_val(
                            &elem_of(&tt),
                            &format!("tn_list_get({}, {}, {})", a.c, i.c, loc(e.pos)),
                        ),
                    ),
                };
                self.tmp(&t, e.pos, init)?
            }
            ExprKind::Call(name, args) => {
                let mut atoms = vec![];
                for a in args {
                    atoms.push(self.expr(a)?);
                }
                let tys: Vec<Type> = args.iter().map(|a| self.ty(a)).collect();
                let init = if let Some(f) = self.funcs.get(name.as_str()).copied() {
                    let cname = if f.tparams.is_empty() {
                        cid(name)
                    } else {
                        let targs = self
                            .types
                            .targs(e)
                            .iter()
                            .map(|t| t.subst(&self.inst))
                            .collect();
                        self.instance(f, targs, e.pos)?
                    };
                    // Functions take ownership of their arguments.
                    let mut cargs: Vec<String> = atoms
                        .iter()
                        .zip(&tys)
                        .map(|(a, t)| self.own(a, t))
                        .collect();
                    cargs.push(loc(e.pos));
                    format!("g_{}({})", cname, cargs.join(", "))
                } else {
                    self.builtin(name, &atoms, &tys, &t, e.pos)?
                };
                self.tmp(&t, e.pos, init)?
            }
        })
    }

    /// `cur.path = val`, taking ownership of `cur` and `val`. Returns an unregistered
    /// C variable holding the updated record.
    fn set_path(
        &mut self,
        cur: &str,
        t: &Type,
        path: &[(String, Pos)],
        val: &str,
    ) -> Result<String, Error> {
        let Type::Record(rn, _) = t else {
            return Err(Error::new(
                "compile",
                path[0].1,
                "field assignment on a non-record",
            ));
        };
        let (f, pos) = &path[0];
        let decl = self.records[rn.as_str()];
        let (i, ft) = decl.field(f).expect("checked");
        let ft = self.field_ty(t, &decl.params, ft);
        let new = if path.len() == 1 {
            val.to_string()
        } else {
            let ct = self.ctype(&ft, *pos)?;
            let inner = self.fresh("u");
            self.line(format!(
                "{} {} = {};",
                ct,
                inner,
                from_val(&ft, &format!("tn_rec_take({}, {})", cur, i))
            ));
            self.set_path(&inner, &ft, &path[1..], val)?
        };
        let ct = self.ctype(t, *pos)?;
        let r = self.fresh("u");
        self.line(format!(
            "{} {} = tn_rec_set({}, {}, {});",
            ct,
            r,
            cur,
            i,
            to_val(&ft, &new)
        ));
        Ok(r)
    }

    fn binop(&mut self, op: BinOp, lt: &Type, a: &str, b: &str, e: &Expr) -> Result<String, Error> {
        use BinOp::*;
        let checked =
            |f: &str| format!("tn_{}({}, {}, {}, {})", f, a, b, loc(e.pos), c_str(&e.text));
        Ok(match (op, lt) {
            (Add, Type::Int) => checked("add"),
            (Add, Type::Str) => format!("tn_str_cat({}, {})", a, b),
            (Add, Type::List(_)) => format!("tn_list_cat({}, {})", a, b),
            (Sub, _) => checked("sub"),
            (Mul, _) => checked("mul"),
            (Div, _) => checked("div"),
            (Mod, _) => checked("mod"),
            (Eq | Ne, _) => {
                let eq = match lt {
                    Type::Str => format!("tn_str_eq({}, {})", a, b),
                    Type::List(_) | Type::Record(..) | Type::Enum(..) => {
                        let d = self.tydesc(lt);
                        format!("tn_eq({}, {}, {})", to_val(lt, a), to_val(lt, b), d)
                    }
                    _ => format!("({} == {})", a, b),
                };
                if op == Ne {
                    format!("!{}", eq)
                } else {
                    eq
                }
            }
            (Lt | Le | Gt | Ge, Type::Str) => {
                format!("(tn_str_cmp({}, {}) {} 0)", a, b, op.symbol())
            }
            (Lt | Le | Gt | Ge, _) => format!("({} {} {})", a, op.symbol(), b),
            _ => {
                return Err(Error::new(
                    "compile",
                    e.pos,
                    format!("cannot compile `{}` on {}", op.symbol(), lt),
                ))
            }
        })
    }

    /// Built-ins borrow their arguments, except `push`, which takes ownership.
    fn builtin(
        &mut self,
        name: &str,
        atoms: &[Atom],
        tys: &[Type],
        t: &Type,
        pos: Pos,
    ) -> Result<String, Error> {
        let at = loc(pos);
        let a: Vec<String> = atoms.iter().map(|x| x.c.clone()).collect();
        Ok(match name {
            "print" => {
                let mut parts = vec![];
                for (x, t) in a.iter().zip(tys) {
                    let d = self.tydesc(t);
                    parts.push(format!("tn_to_str({}, {}, false)", to_val(t, x), d));
                }
                if parts.is_empty() {
                    "tn_print(0, NULL)".into()
                } else {
                    format!(
                        "tn_print({}, (tn_str *[]){{{}}})",
                        parts.len(),
                        parts.join(", ")
                    )
                }
            }
            "input" => format!(
                "tn_input({}, {})",
                a.first().map_or("NULL", |s| s.as_str()),
                at
            ),
            "len" => match tys[0] {
                Type::Str => format!("tn_str_len({})", a[0]),
                _ => format!("{}->len", a[0]),
            },
            "str" => {
                let d = self.tydesc(&tys[0]);
                format!("tn_to_str({}, {}, false)", to_val(&tys[0], &a[0]), d)
            }
            "int" => match tys[0] {
                Type::Str => format!("tn_parse_int({}, {})", a[0], at),
                _ => a[0].clone(),
            },
            "abs" => format!("tn_abs({}, {})", a[0], at),
            "parse_int" => {
                let d = self.tydesc(t);
                format!("tn_try_parse_int({}, {})", a[0], d)
            }
            "push" => {
                let elem = elem_of(t);
                let list = self.own(&atoms[0], t);
                let item = self.own(&atoms[1], &elem);
                format!("tn_list_push({}, {})", list, to_val(&elem, &item))
            }
            "range" if a.len() == 1 => format!("tn_range(INT64_C(0), {})", a[0]),
            "range" => format!("tn_range({}, {})", a[0], a[1]),
            "join" => {
                let d = self.tydesc(&elem_of(&tys[0]));
                format!("tn_join({}, {}, {})", a[0], d, a[1])
            }
            "split" => format!("tn_split({}, {}, {})", a[0], a[1], at),
            "contains" => match tys[0] {
                Type::Str => format!("tn_str_contains({}, {})", a[0], a[1]),
                _ => {
                    let elem = elem_of(&tys[0]);
                    let d = self.tydesc(&elem);
                    format!(
                        "tn_list_contains({}, {}, {})",
                        a[0],
                        to_val(&elem, &a[1]),
                        d
                    )
                }
            },
            "read_file" => format!("tn_read_file({}, {})", a[0], at),
            "write_file" => format!("tn_write_file({}, {}, {})", a[0], a[1], at),
            "now" => "tn_now()".into(),
            "sleep" => format!("tn_sleep({}, {})", a[0], at),
            "random" => format!("tn_random({}, {})", a[0], at),
            _ => {
                return Err(Error::new(
                    "compile",
                    pos,
                    format!("unknown built-in `{}`", name),
                ))
            }
        })
    }
}

/// True when `e` contains the field read `name.field`.
fn reads_field(e: &Expr, name: &str, field: &str) -> bool {
    let any = |xs: &[Expr]| xs.iter().any(|x| reads_field(x, name, field));
    match &e.kind {
        ExprKind::Field(t, f) => {
            (f == field && matches!(&t.kind, ExprKind::Var(n) if n == name))
                || reads_field(t, name, field)
        }
        ExprKind::List(xs) | ExprKind::Call(_, xs) => any(xs),
        ExprKind::Unary(_, x) => reads_field(x, name, field),
        ExprKind::Binary(_, l, r) | ExprKind::Index(l, r) => {
            reads_field(l, name, field) || reads_field(r, name, field)
        }
        ExprKind::Record(_, fs) | ExprKind::Variant(_, fs) => {
            fs.iter().any(|(_, x, _)| reads_field(x, name, field))
        }
        _ => false,
    }
}

/// True when `e` reads variable `name` exactly once, and not only conditionally
/// (on the right of `and` / `or`).
fn reads_once(e: &Expr, name: &str) -> bool {
    fn walk(e: &Expr, name: &str, conditional: bool, count: &mut usize, cond_read: &mut bool) {
        let mut go = |x: &Expr, c: bool| walk(x, name, c, count, cond_read);
        match &e.kind {
            ExprKind::Var(n) if n == name => {
                *count += 1;
                if conditional {
                    *cond_read = true;
                }
            }
            ExprKind::Int(_) | ExprKind::Str(_) | ExprKind::Bool(_) | ExprKind::Var(_) => {}
            ExprKind::List(xs) | ExprKind::Call(_, xs) => {
                xs.iter().for_each(|x| go(x, conditional))
            }
            ExprKind::Unary(_, x) | ExprKind::Field(x, _) => go(x, conditional),
            ExprKind::Binary(BinOp::And | BinOp::Or, l, r) => {
                go(l, conditional);
                go(r, true);
            }
            ExprKind::Binary(_, l, r) | ExprKind::Index(l, r) => {
                go(l, conditional);
                go(r, conditional);
            }
            ExprKind::Record(_, fs) | ExprKind::Variant(_, fs) => {
                fs.iter().for_each(|(_, x, _)| go(x, conditional))
            }
        }
    }
    let (mut count, mut cond_read) = (0, false);
    walk(e, name, false, &mut count, &mut cond_read);
    count == 1 && !cond_read
}
